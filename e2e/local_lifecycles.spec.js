test('Fees: Teacher collection, Admin approval and Student/Parent receipts', async ({ browser }) => {
  const name = `UI fee ${Date.now()}`
  const adminContext = await browser.newContext({ viewport })
  const admin = await adminContext.newPage()
  await login(admin, 'admin')
  await navigate(admin, 'Fees')
  const setup = form(admin, 'Create fee structure')
  await fill(setup, { 'Fee name *': name, 'Academic year *': '2030-2031', 'Amount *': '100', 'Due date *': '2030-03-01', Description: 'Synthetic cash collection verification.' })
  await choose(setup, 'Class *', 'Grade 5')
  await setup.getByRole('button', { name: 'Create fee', exact: true }).click()
  await admin.locator('.fee-structure-list article').filter({ hasText: name }).getByRole('button', { name: 'Generate invoices' }).click()
  await admin.getByRole('alertdialog').getByRole('button', { name: 'Generate invoices', exact: true }).click()
  const invoice = admin.locator('.fee-table tr').filter({ hasText: name }).filter({ hasText: 'Aarav Demo' })
  await expect(invoice.locator('.delivery-status')).toHaveText('pending')
  const teacherContext = await browser.newContext({ viewport })
  const teacher = await teacherContext.newPage()
  await login(teacher, 'teacher')
  await navigate(teacher, 'Fee Collection')
  await choose(teacher, 'Student invoice *', new RegExp(`Aarav Demo.*${name}`))
  await fill(teacher.locator('form'), { 'Amount collected *': '100', Reference: name, Notes: 'Synthetic local record; no money transferred.' })
  await teacher.getByRole('button', { name: 'Send for admin approval', exact: true }).click()
  await expect(teacher.locator('tr').filter({ hasText: name }).locator('.delivery-status')).toHaveText('pending')
  await noErrors(teacher)
  await teacherContext.close()
  await navigate(admin, 'Overview')
  await navigate(admin, 'Fees')
  const request = admin.locator('.fee-collection-requests tr').filter({ hasText: name })
  await request.getByRole('button', { name: 'Approve', exact: true }).click()
  await expect(request).toHaveCount(0)
  // Approval must refresh the invoice register without navigating away.
  await expect(invoice.locator('.delivery-status')).toHaveText('paid')
  await noErrors(admin)
  await adminContext.close()
  for (const role of ['student', 'parent']) {
    const context = await browser.newContext({ viewport })
    const page = await context.newPage()
    await login(page, role)
    await navigate(page, 'My Portal')
    await page.locator('.portal-tabs').getByRole('button', { name: 'Fees', exact: true }).click()
    const row = page.locator('.portal-action-panel tr').filter({ hasText: name })
    await expect(row.locator('.status-pill')).toHaveText('Paid')
    await expect(row.locator('td').nth(4)).toHaveText(/^₹0(?:\.00)?$/)
    const download = page.waitForEvent('download')
    await row.getByRole('button', { name: 'Receipt', exact: true }).click()
    const receipt = await download
    expect(receipt.suggestedFilename()).toMatch(/\.html$/)
    expect(await readFile(await receipt.path(), 'utf8')).toContain(name)
    await noErrors(page)
    await context.close()
  }
})

async function login(page, role) {
  await page.goto(`${env.WEB_E2E_BASE_URL || 'http://127.0.0.1:5173'}/login`)
  // A fresh browser context is used for each identity; no existing session is overwritten.
  await page.locator('[name=school_domain]').fill('eduflow_demo_local')
  await page.locator('[name=email]').fill(`local.${role}@eduflow.test`)
  await page.locator('[name=password]').fill(env.LOCAL_FINAL_PASSWORD)
  await page.getByRole('button', { name: 'Sign in securely' }).click()
  await expect(page.locator('.dashboard-main')).toBeVisible()
  await expect(page.locator('.session-feedback-backdrop')).toBeHidden()
}

async function navigate(page, name) {
  const menu = page.getByRole('button', { name: 'Open navigation', exact: true })
  if (await menu.isVisible()) await menu.click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click()
  await expect(page.locator('.dashboard-header h1')).toHaveText(name)
  await expect(page.locator('.loading-grid')).toBeHidden()
}

const form = (page, title) => page.locator('form').filter({ has: page.getByRole('heading', { name: title }) })
async function fill(scope, values) {
  for (const [name, value] of Object.entries(values)) await scope.getByLabel(name, { exact: true }).fill(value)
}
async function choose(scope, label, text) {
  const select = scope.getByRole('combobox', { name: label, exact: true })
  const option = select.locator('option').filter({ hasText: text })
  await expect(option).toHaveCount(1)
  await select.selectOption(await option.getAttribute('value'))
}
async function noErrors(page) {
  await expect(page.locator('.form-error,.api-notice')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(viewport.width + 1)
}

